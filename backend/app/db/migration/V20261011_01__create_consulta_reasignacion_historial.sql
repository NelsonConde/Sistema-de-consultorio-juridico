BEGIN;

CREATE TABLE IF NOT EXISTS "DB_consultorioJuridico".consulta_reasignacion_historial (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    consulta_id BIGINT NOT NULL,
    tipo_responsable VARCHAR(20) NOT NULL,
    responsable_anterior_id BIGINT,
    responsable_nuevo_id BIGINT NOT NULL,
    motivo TEXT NOT NULL,
    actor_usuario_id BIGINT NOT NULL,
    ocurrido_en TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

ALTER TABLE "DB_consultorioJuridico".consulta_reasignacion_historial
    DROP CONSTRAINT IF EXISTS fk_reasignacion_historial_consulta,
    DROP CONSTRAINT IF EXISTS fk_reasignacion_historial_actor,
    DROP CONSTRAINT IF EXISTS ck_reasignacion_historial_tipo,
    DROP CONSTRAINT IF EXISTS ck_reasignacion_historial_anterior_positivo,
    DROP CONSTRAINT IF EXISTS ck_reasignacion_historial_nuevo_positivo,
    DROP CONSTRAINT IF EXISTS ck_reasignacion_historial_responsables_distintos,
    DROP CONSTRAINT IF EXISTS ck_reasignacion_historial_motivo;

ALTER TABLE "DB_consultorioJuridico".consulta_reasignacion_historial
    ADD CONSTRAINT fk_reasignacion_historial_consulta
        FOREIGN KEY (consulta_id)
        REFERENCES "DB_consultorioJuridico".consulta (id)
        ON UPDATE RESTRICT ON DELETE RESTRICT,
    ADD CONSTRAINT fk_reasignacion_historial_actor
        FOREIGN KEY (actor_usuario_id)
        REFERENCES "DB_consultorioJuridico".usuario_sistema (id)
        ON UPDATE RESTRICT ON DELETE RESTRICT,
    ADD CONSTRAINT ck_reasignacion_historial_tipo
        CHECK (tipo_responsable IN ('ESTUDIANTE', 'ASESOR', 'MONITOR')),
    ADD CONSTRAINT ck_reasignacion_historial_anterior_positivo
        CHECK (responsable_anterior_id IS NULL OR responsable_anterior_id > 0),
    ADD CONSTRAINT ck_reasignacion_historial_nuevo_positivo
        CHECK (responsable_nuevo_id > 0),
    ADD CONSTRAINT ck_reasignacion_historial_responsables_distintos
        CHECK (responsable_anterior_id IS NULL OR responsable_anterior_id <> responsable_nuevo_id),
    ADD CONSTRAINT ck_reasignacion_historial_motivo
        CHECK (LENGTH(BTRIM(motivo)) > 0);

CREATE INDEX IF NOT EXISTS idx_reasignacion_historial_consulta_fecha
    ON "DB_consultorioJuridico".consulta_reasignacion_historial
    (consulta_id, ocurrido_en DESC, id DESC);

CREATE INDEX IF NOT EXISTS idx_reasignacion_historial_actor_fecha
    ON "DB_consultorioJuridico".consulta_reasignacion_historial
    (actor_usuario_id, ocurrido_en DESC);

CREATE OR REPLACE FUNCTION "DB_consultorioJuridico".validar_responsables_reasignacion_consulta()
RETURNS TRIGGER
LANGUAGE plpgsql
AS $$
DECLARE
    responsable_nuevo_existe BOOLEAN;
    responsable_anterior_existe BOOLEAN := TRUE;
BEGIN
    CASE NEW.tipo_responsable
        WHEN 'ESTUDIANTE' THEN
            SELECT EXISTS (
                SELECT 1 FROM "DB_consultorioJuridico".estudiante
                WHERE id = NEW.responsable_nuevo_id
            ) INTO responsable_nuevo_existe;
            IF NEW.responsable_anterior_id IS NOT NULL THEN
                SELECT EXISTS (
                    SELECT 1 FROM "DB_consultorioJuridico".estudiante
                    WHERE id = NEW.responsable_anterior_id
                ) INTO responsable_anterior_existe;
            END IF;
        WHEN 'ASESOR' THEN
            SELECT EXISTS (
                SELECT 1 FROM "DB_consultorioJuridico".asesor
                WHERE id = NEW.responsable_nuevo_id
            ) INTO responsable_nuevo_existe;
            IF NEW.responsable_anterior_id IS NOT NULL THEN
                SELECT EXISTS (
                    SELECT 1 FROM "DB_consultorioJuridico".asesor
                    WHERE id = NEW.responsable_anterior_id
                ) INTO responsable_anterior_existe;
            END IF;
        WHEN 'MONITOR' THEN
            SELECT EXISTS (
                SELECT 1 FROM "DB_consultorioJuridico".monitor
                WHERE id = NEW.responsable_nuevo_id
            ) INTO responsable_nuevo_existe;
            IF NEW.responsable_anterior_id IS NOT NULL THEN
                SELECT EXISTS (
                    SELECT 1 FROM "DB_consultorioJuridico".monitor
                    WHERE id = NEW.responsable_anterior_id
                ) INTO responsable_anterior_existe;
            END IF;
        ELSE
            RAISE EXCEPTION 'Tipo de responsable no soportado: %', NEW.tipo_responsable
                USING ERRCODE = '23514';
    END CASE;

    IF NOT responsable_nuevo_existe THEN
        RAISE EXCEPTION 'El responsable nuevo % no existe para el tipo %',
            NEW.responsable_nuevo_id, NEW.tipo_responsable
            USING ERRCODE = '23503';
    END IF;

    IF NOT responsable_anterior_existe THEN
        RAISE EXCEPTION 'El responsable anterior % no existe para el tipo %',
            NEW.responsable_anterior_id, NEW.tipo_responsable
            USING ERRCODE = '23503';
    END IF;

    RETURN NEW;
END;
$$;

CREATE OR REPLACE FUNCTION "DB_consultorioJuridico".prevenir_modificacion_historial_reasignacion()
RETURNS TRIGGER
LANGUAGE plpgsql
AS $$
BEGIN
    RAISE EXCEPTION 'El historial de reasignaciones es inmutable: no se permite %', TG_OP
        USING ERRCODE = '55000';
END;
$$;

DROP TRIGGER IF EXISTS trg_validar_responsables_reasignacion
    ON "DB_consultorioJuridico".consulta_reasignacion_historial;
CREATE TRIGGER trg_validar_responsables_reasignacion
    BEFORE INSERT ON "DB_consultorioJuridico".consulta_reasignacion_historial
    FOR EACH ROW
    EXECUTE FUNCTION "DB_consultorioJuridico".validar_responsables_reasignacion_consulta();

DROP TRIGGER IF EXISTS trg_historial_reasignacion_inmutable
    ON "DB_consultorioJuridico".consulta_reasignacion_historial;
CREATE TRIGGER trg_historial_reasignacion_inmutable
    BEFORE UPDATE OR DELETE ON "DB_consultorioJuridico".consulta_reasignacion_historial
    FOR EACH ROW
    EXECUTE FUNCTION "DB_consultorioJuridico".prevenir_modificacion_historial_reasignacion();

COMMENT ON TABLE "DB_consultorioJuridico".consulta_reasignacion_historial IS
    'Eventos inmutables de reasignación individual de responsables de consultas jurídicas.';
COMMENT ON COLUMN "DB_consultorioJuridico".consulta_reasignacion_historial.responsable_anterior_id IS
    'Identificador polimórfico validado contra la tabla correspondiente a tipo_responsable.';
COMMENT ON COLUMN "DB_consultorioJuridico".consulta_reasignacion_historial.responsable_nuevo_id IS
    'Identificador polimórfico validado contra la tabla correspondiente a tipo_responsable.';

COMMIT;
